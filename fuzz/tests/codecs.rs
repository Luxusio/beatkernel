#[test]
fn room_independent_literals_and_malformed_frames_classify_correctly() {
    for tag in [4, 5, 6] {
        let literal = [66, 75, 77, 82, 2, 0, tag, 0, 0, 0, 0];
        let expected = match tag {
            4 => RoomMessage::Seal,
            5 => RoomMessage::Ready,
            _ => RoomMessage::Leave,
        };
        assert_eq!(decode_message(&literal).unwrap(), expected);
        assert!(check_room(&literal));
    }
    for message in room_cases() {
        let bytes = encode_message(&message).unwrap();
        for cut in 0..bytes.len() {
            assert!(!check_room(&bytes[..cut]));
        }
        let mut trailing = bytes.clone();
        trailing.push(0);
        assert!(!check_room(&trailing));
        for offset in [0, 4, 6] {
            let mut invalid = bytes.clone();
            invalid[offset] = 255;
            assert!(decode_message(&invalid).is_err());
            assert!(!check_room(&invalid));
        }
        let mut invalid_extent = bytes;
        invalid_extent[7..11].copy_from_slice(&u32::MAX.to_le_bytes());
        assert!(decode_message(&invalid_extent).is_err());
        assert!(!check_room(&invalid_extent));
    }
    assert!(!check_room(&vec![0; 131_073]));
}

#[test]
fn room_syntactically_complete_invalid_values_are_refused() {
    // Valid extents alone do not make participant zero or negative clock time valid.
    for (tag, payload) in [
        (2, vec![0; 8]),
        (7, [1u64.to_le_bytes(), (-1i64).to_le_bytes()].concat()),
        (9, (-1i64).to_le_bytes().to_vec()),
        (15, [1u64.to_le_bytes(), 0u64.to_le_bytes()].concat()),
    ] {
        let mut frame = vec![66, 75, 77, 82, 2, 0, tag];
        frame.extend_from_slice(&(payload.len() as u32).to_le_bytes());
        frame.extend_from_slice(&payload);
        assert!(decode_message(&frame).is_err());
        assert!(!check_room(&frame));
    }
    let valid = encode_message(&RoomMessage::Join {
        identity: vec![17],
        players: vec![PlayerId(1)],
    })
    .unwrap();
    assert!(check_room(&valid));
    let mut zero_player = valid.clone();
    zero_player[17..21].fill(0);
    assert!(decode_message(&zero_player).is_err());
    assert!(!check_room(&zero_player));
    let mut zero_count = valid;
    zero_count[16] = 0;
    assert!(decode_message(&zero_count).is_err());
    assert!(!check_room(&zero_count));
}
