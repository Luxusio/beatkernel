fn meta() -> EventMeta {
    EventMeta {
        source: DeviceId(u64::MAX),
        timestamp: Timestamp::MIN,
        clock_domain: ClockDomainId(3),
        sequence: u64::MAX,
        native: Some(NativeEventMeta {
            backend: BackendId(u32::MAX),
            code: Some(0),
            timestamp: Some(ClockPoint {
                domain: ClockDomainId(77),
                timestamp: Timestamp::MAX,
            }),
        }),
        original_clock_point: Some(ClockPoint {
            domain: ClockDomainId(91),
            timestamp: Timestamp::from_nanos(-99),
        }),
    }
}

fn physical_cases() -> Vec<PhysicalInputEvent> {
    let meta = meta();
    let control = PhysicalControlId::Vendor {
        namespace: VendorNamespaceId(33),
        code: 44,
    };
    let mut cases = vec![];
    for state in [ButtonState::Down, ButtonState::Up, ButtonState::Repeat] {
        cases.push(PhysicalInputEvent::Button(ButtonEvent {
            meta,
            control,
            state,
        }));
    }
    // Both NaN signs/payloads, signaling NaNs, zero signs, infinities and subnormal.
    for bits in [
        0,
        0x8000_0000,
        0x7fc1_2345,
        0xffc5_4321,
        0x7fa1_2345,
        0xffa0_0001,
        1,
        0x7f80_0000,
        0xff80_0000,
    ] {
        for mode in [AxisMode::Absolute, AxisMode::Relative] {
            cases.push(PhysicalInputEvent::Axis(AxisEvent {
                meta,
                control,
                value: f32::from_bits(bits),
                mode,
            }));
        }
    }
    for phase in [
        TouchPhase::Down,
        TouchPhase::Move,
        TouchPhase::Up,
        TouchPhase::Cancel,
    ] {
        for pressure in [None, Some(f32::from_bits(0x7fa1_2345)), Some(-0.0)] {
            cases.push(PhysicalInputEvent::Touch(TouchEvent {
                meta,
                control,
                contact: ContactId(u64::MAX),
                phase,
                position: Position2 {
                    x: f32::from_bits(0xffc5_4321),
                    y: 0.0,
                },
                pressure,
            }));
        }
    }
    for mode in [PointerMode::Absolute, PointerMode::Relative] {
        cases.push(PhysicalInputEvent::Pointer(PointerEvent {
            meta,
            control,
            mode,
            position: Position2 {
                x: -0.0,
                y: f32::from_bits(0x7fa1_2345),
            },
        }));
    }
    cases.push(PhysicalInputEvent::Pose(PoseEvent {
        meta,
        control,
        position: Position3 {
            x: 0.0,
            y: -0.0,
            z: f32::from_bits(1),
        },
        orientation: Quaternion {
            x: f32::from_bits(0x7fc1_2345),
            y: f32::from_bits(0xffa0_0001),
            z: f32::INFINITY,
            w: f32::NEG_INFINITY,
        },
    }));
    for report_id in [None, Some(0), Some(255)] {
        cases.push(PhysicalInputEvent::RawHidReport(RawHidReportEvent {
            meta,
            report_id,
            data: vec![0, 255, 17],
        }));
    }
    cases.push(PhysicalInputEvent::Custom(CustomInputEvent {
        meta,
        namespace: VendorNamespaceId(u32::MAX),
        type_id: u32::MAX,
        payload: vec![255, 0, 128],
    }));
    cases
}

// Compare fields directly against the constructed event, never float PartialEq
// or bytes generated by the same encoder as their own correctness oracle.
fn assert_physical(expected: &PhysicalInputEvent, actual: &PhysicalInputEvent) {
    assert_eq!(actual.meta(), expected.meta());
    match (expected, actual) {
        (PhysicalInputEvent::Axis(a), PhysicalInputEvent::Axis(b)) => {
            assert_eq!(b.control, a.control);
            assert_eq!(b.mode, a.mode);
            assert_eq!(b.value.to_bits(), a.value.to_bits());
        }
        (PhysicalInputEvent::Touch(a), PhysicalInputEvent::Touch(b)) => {
            assert_eq!(
                (b.control, b.contact, b.phase),
                (a.control, a.contact, a.phase)
            );
            assert_eq!(
                (b.position.x.to_bits(), b.position.y.to_bits()),
                (a.position.x.to_bits(), a.position.y.to_bits())
            );
            assert_eq!(b.pressure.map(f32::to_bits), a.pressure.map(f32::to_bits));
        }
        (PhysicalInputEvent::Pointer(a), PhysicalInputEvent::Pointer(b)) => {
            assert_eq!((b.control, b.mode), (a.control, a.mode));
            assert_eq!(
                (b.position.x.to_bits(), b.position.y.to_bits()),
                (a.position.x.to_bits(), a.position.y.to_bits())
            );
        }
        (PhysicalInputEvent::Pose(a), PhysicalInputEvent::Pose(b)) => {
            assert_eq!(b.control, a.control);
            assert_eq!(
                [
                    b.position.x.to_bits(),
                    b.position.y.to_bits(),
                    b.position.z.to_bits(),
                    b.orientation.x.to_bits(),
                    b.orientation.y.to_bits(),
                    b.orientation.z.to_bits(),
                    b.orientation.w.to_bits()
                ],
                [
                    a.position.x.to_bits(),
                    a.position.y.to_bits(),
                    a.position.z.to_bits(),
                    a.orientation.x.to_bits(),
                    a.orientation.y.to_bits(),
                    a.orientation.z.to_bits(),
                    a.orientation.w.to_bits()
                ]
            );
        }
        (PhysicalInputEvent::Button(a), PhysicalInputEvent::Button(b)) => assert_eq!(b, a),
        (PhysicalInputEvent::RawHidReport(a), PhysicalInputEvent::RawHidReport(b)) => {
            assert_eq!(b, a)
        }
        (PhysicalInputEvent::Custom(a), PhysicalInputEvent::Custom(b)) => assert_eq!(b, a),
        _ => panic!("physical variant changed"),
    }
}

fn replay(events: Vec<PhysicalInputEvent>) -> ReplayFile {
    let mut records: Vec<_> = events
        .into_iter()
        .enumerate()
        .map(|(index, physical)| ReplayRecord {
            ordinal: index as u64,
            song_time: Timestamp::from_nanos(index as i64),
            operation: ReplayOperation::Input(GameInputEvent {
                game_control: GameControlId(u32::MAX),
                physical,
            }),
        })
        .collect();
    records.push(ReplayRecord {
        ordinal: records.len() as u64,
        song_time: Timestamp::MAX,
        operation: ReplayOperation::Advance,
    });
    let mut file = ReplayFile::new(
        ReplayHeader {
            version: REPLAY_VERSION,
            chart_identity: vec![0, 255, 17],
            rules_identity: vec![128, 0],
            options: vec![0, 255],
            seed: u64::MAX,
            normalized_clock: ClockDomainId(3),
        },
        records,
    );
    file.runtime_version = "independent-fixture/v1".into();
    file.calibration_metadata = Some(vec![255, 0, 17]);
    file
}

