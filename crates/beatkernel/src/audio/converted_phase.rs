//! Bounded generated converter correspondence, without native presentation proof.

use super::{
    AudioError, ConvertedOutputState, InterpolatedTargetTime, SourcePlaybackSpan,
    SourcePlaybackState, SourcePosition, TargetTime,
};
use core::cmp::Ordering;

/// Refusal of a generated-coordinate lookup or exact elapsed calculation.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum ConvertedPhaseError {
    /// A transferred descriptor has an invalid rate, fraction or state.
    InvalidDescriptor,
    /// The supplied upper bound precedes the segment start.
    InvalidRange,
    /// The coordinate precedes the owner's actual retained lower bound.
    BeforeRetainedRange,
    /// The coordinate has not been generated by this owner.
    AfterGeneratedRange,
    /// The physical or active playback coordinate precedes the requested cut.
    NegativeElapsed,
    /// The exact signed result exceeds the elapsed nanosecond representation.
    Overflow,
}

#[derive(Clone, Copy, Debug)]
struct Segment {
    start: TargetTime,
    source: SourcePosition,
    state: ConvertedOutputState,
}

/// Transferable mathematical correspondence of an actual generated segment.
/// Decoding validates its structure, not its owner, native admission or
/// presentation. Publishers must retain those proofs with the descriptor and
/// qualify its upper bound against actual generated and submitted progress.
#[derive(Clone, Copy, Debug)]
pub struct ConvertedPhaseSpan {
    source_rate: u32,
    segment: Segment,
}

impl ConvertedPhaseSpan {
    /// Checks the exact interpolated coordinate against the caller-qualified
    /// range, then floors physical source duration relative to a cut once.
    /// This authenticates neither native submission nor mixer pause removal.
    pub fn elapsed_nanos_at_interpolated_time(
        self,
        query: InterpolatedTargetTime,
        qualified_end: TargetTime,
        cut: u64,
    ) -> Result<i128, ConvertedPhaseError> {
        self.validate_interpolated_range(query, qualified_end)?;
        query.elapsed_at_source(
            self.segment.source,
            self.source_rate,
            self.segment.start,
            self.segment.state == ConvertedOutputState::Active,
            cut,
        )
    }

    /// Orders the exact physical source coordinate against an integer frame.
    /// No nanosecond floor or native pause/presentation qualification is applied.
    pub fn compare_source_frame_at_interpolated_time(
        self,
        query: InterpolatedTargetTime,
        qualified_end: TargetTime,
        frame: u64,
    ) -> Result<Ordering, ConvertedPhaseError> {
        self.validate_interpolated_range(query, qualified_end)?;
        self.compare_source_frame(query, frame)
    }

    /// Maps an exact physical coordinate through a caller-qualified half-open
    /// source interval, then floors relative active playback duration once.
    /// A converter Held segment alone does not imply frozen playback or an ACK.
    pub fn playback_elapsed_nanos_at_interpolated_time(
        self,
        query: InterpolatedTargetTime,
        qualified_end: TargetTime,
        playback: SourcePlaybackSpan,
        active_cut: u64,
    ) -> Result<i128, ConvertedPhaseError> {
        self.validate_interpolated_range(query, qualified_end)?;
        if self
            .compare_source_frame(query, playback.physical_start())?
            .is_lt()
        {
            return Err(ConvertedPhaseError::BeforeRetainedRange);
        }
        if let Some(end) = playback.physical_end() {
            if !self.compare_source_frame(query, end)?.is_lt() {
                return Err(ConvertedPhaseError::AfterGeneratedRange);
            }
        }
        match playback.state() {
            SourcePlaybackState::Running => {
                // The effective physical cut can exceed u64 even when the
                // final playback duration is representable.
                let cut = i128::from(playback.physical_start()) + i128::from(active_cut)
                    - i128::from(playback.playback_start());
                query.elapsed_at_source_cut(
                    self.segment.source,
                    self.source_rate,
                    self.segment.start,
                    self.segment.state == ConvertedOutputState::Active,
                    cut,
                )
            }
            SourcePlaybackState::Frozen => query.elapsed_at_source_cut(
                SourcePosition {
                    frame: playback.playback_start(),
                    numerator: 0,
                    denominator: 1,
                },
                self.source_rate,
                self.segment.start,
                false,
                i128::from(active_cut),
            ),
        }
    }

    fn compare_source_frame(
        self,
        query: InterpolatedTargetTime,
        frame: u64,
    ) -> Result<Ordering, ConvertedPhaseError> {
        query.compare_source_frame(
            self.segment.source,
            self.source_rate,
            self.segment.start,
            self.segment.state == ConvertedOutputState::Active,
            frame,
        )
    }

    fn validate_interpolated_range(
        self,
        query: InterpolatedTargetTime,
        qualified_end: TargetTime,
    ) -> Result<(), ConvertedPhaseError> {
        if compare_time(qualified_end, self.segment.start).is_lt() {
            return Err(ConvertedPhaseError::InvalidRange);
        }
        if query.compare_target_time(self.segment.start).is_lt() {
            return Err(ConvertedPhaseError::BeforeRetainedRange);
        }
        if query.compare_target_time(qualified_end).is_gt() {
            return Err(ConvertedPhaseError::AfterGeneratedRange);
        }
        Ok(())
    }

    /// Fixed words: source Hz/frame/numerator/denominator, target
    /// seconds/numerator/denominator, then state (active 0, held 1).
    pub const fn to_words(self) -> [u64; 8] {
        [
            self.source_rate as u64,
            self.segment.source.frame,
            self.segment.source.numerator,
            self.segment.source.denominator,
            self.segment.start.seconds(),
            self.segment.start.numerator(),
            self.segment.start.denominator(),
            match self.segment.state {
                ConvertedOutputState::Active => 0,
                ConvertedOutputState::Held => 1,
            },
        ]
    }

    /// Validates only the transferred mathematical descriptor. In particular,
    /// a valid descriptor is not evidence that these samples were generated.
    pub fn from_words(words: [u64; 8]) -> Result<Self, ConvertedPhaseError> {
        let source_rate = u32::try_from(words[0])
            .ok()
            .filter(|rate| *rate != 0)
            .ok_or(ConvertedPhaseError::InvalidDescriptor)?;
        if words[3] == 0 || words[2] >= words[3] {
            return Err(ConvertedPhaseError::InvalidDescriptor);
        }
        let start = TargetTime::new(words[4], words[5], words[6])
            .map_err(|_| ConvertedPhaseError::InvalidDescriptor)?;
        let state = match words[7] {
            0 => ConvertedOutputState::Active,
            1 => ConvertedOutputState::Held,
            _ => return Err(ConvertedPhaseError::InvalidDescriptor),
        };
        Ok(Self {
            source_rate,
            segment: Segment {
                start,
                source: SourcePosition {
                    frame: words[1],
                    numerator: words[2],
                    denominator: words[3],
                },
                state,
            },
        })
    }

    /// Checks `start <= query <= qualified_end` before computing a point.
    /// The caller owns the native/owner qualification of the supplied end;
    /// this method checks its mathematical range only.
    pub fn point(
        self,
        query: TargetTime,
        qualified_end: TargetTime,
    ) -> Result<ConvertedPhasePoint, ConvertedPhaseError> {
        if compare_time(qualified_end, self.segment.start).is_lt() {
            return Err(ConvertedPhaseError::InvalidRange);
        }
        if compare_time(query, self.segment.start).is_lt() {
            return Err(ConvertedPhaseError::BeforeRetainedRange);
        }
        if compare_time(query, qualified_end).is_gt() {
            return Err(ConvertedPhaseError::AfterGeneratedRange);
        }
        Ok(ConvertedPhasePoint {
            source_rate: self.source_rate,
            segment: self.segment,
            time: query,
        })
    }
}

/// Cold-reserved transition history of one complete conversion owner.
/// Ordinary callbacks and continuous rate changes consume no extra segments.
/// These are generated facts; callers must separately qualify native admission,
/// presentation and any mixer pause silence removal.
#[derive(Debug)]
pub struct ConvertedPhaseHistory {
    source_rate: u32,
    initial_time: TargetTime,
    initial_source: SourcePosition,
    end_time: TargetTime,
    end_source: SourcePosition,
    capacity: usize,
    segments: Vec<Segment>,
    retirement_revision: u64,
}

impl ConvertedPhaseHistory {
    pub(super) fn new(
        source_rate: u32,
        time: TargetTime,
        source: SourcePosition,
        capacity: usize,
    ) -> Result<Self, AudioError> {
        if capacity == 0 {
            return Err(AudioError::InvalidCapacity);
        }
        let mut segments = Vec::new();
        segments
            .try_reserve_exact(capacity)
            .map_err(|_| AudioError::AllocationFailed)?;
        Ok(Self {
            source_rate,
            initial_time: time,
            initial_source: source,
            end_time: time,
            end_source: source,
            capacity,
            segments,
            retirement_revision: 0,
        })
    }

    /// Number of retained nonempty active/held transition segments.
    pub fn len(&self) -> usize {
        self.segments.len()
    }
    /// Whether only the initial exact point has been retained.
    pub fn is_empty(&self) -> bool {
        self.segments.is_empty()
    }
    /// Maximum number of transitions before explicit generation refusal.
    pub const fn capacity(&self) -> usize {
        self.capacity
    }
    /// Immutable cold initial target time, including after prefix retirement.
    pub const fn start_time(&self) -> TargetTime {
        self.initial_time
    }
    /// Inclusive lower bound of the actual retained generated correspondence.
    /// An empty cold history retains only its initial exact point.
    pub fn retained_start_time(&self) -> TargetTime {
        self.segments
            .first()
            .map_or(self.initial_time, |segment| segment.start)
    }
    /// Checked mathematical prefix-retirement nonce, initially zero.
    /// This is not native publication coherence, freshness or acknowledgment.
    pub const fn retirement_revision(&self) -> u64 {
        self.retirement_revision
    }
    /// Checks the same exact range and checked nonce as `retire_before`
    /// without mutation or allocation. This mathematical check grants no
    /// consumer qualification or native retirement permission.
    pub fn validate_retirement_before(&self, pin: TargetTime) -> Result<(), AudioError> {
        let removed = self.retirement_count(pin)?;
        self.checked_retirement_revision(removed)?;
        Ok(())
    }
    /// Drops complete segments before the segment covering `pin`, retaining
    /// that predecessor and every later segment, including the final segment.
    /// The owning thread must qualify the minimum exact pin required by all
    /// live consumers. This operation supplies no native or input-drain proof.
    /// Refusal preserves the history; successful retirement does not allocate,
    /// rebase source positions or change the immutable cold creation metadata.
    pub fn retire_before(&mut self, pin: TargetTime) -> Result<usize, AudioError> {
        let removed = self.retirement_count(pin)?;
        let revision = self.checked_retirement_revision(removed)?;
        if removed == 0 {
            return Ok(0);
        }
        drop(self.segments.drain(..removed));
        self.retirement_revision = revision;
        Ok(removed)
    }

    fn retirement_count(&self, pin: TargetTime) -> Result<usize, AudioError> {
        if compare_time(pin, self.retained_start_time()).is_lt()
            || compare_time(pin, self.end_time).is_gt()
        {
            return Err(AudioError::InvalidFormat);
        }
        let count = self
            .segments
            .partition_point(|segment| !compare_time(segment.start, pin).is_gt());
        Ok(count.saturating_sub(1))
    }

    fn checked_retirement_revision(&self, removed: usize) -> Result<u64, AudioError> {
        if removed == 0 {
            return Ok(self.retirement_revision);
        }
        self.retirement_revision
            .checked_add(1)
            .ok_or(AudioError::Overflow)
    }
    /// Original immutable source frames per second.
    pub const fn source_rate(&self) -> u32 {
        self.source_rate
    }
    /// Exact source coordinate of the cold initial point. This point does not
    /// constitute a generated active or held segment.
    pub const fn initial_source_position(&self) -> SourcePosition {
        self.initial_source
    }
    /// An actual nonempty generated segment start, in transition order.
    /// The next span start or the history's generated end bounds this span.
    pub fn span(&self, index: usize) -> Option<ConvertedPhaseSpan> {
        self.segments
            .get(index)
            .copied()
            .map(|segment| ConvertedPhaseSpan {
                source_rate: self.source_rate,
                segment,
            })
    }
    /// Inclusive generated upper bound.
    pub const fn end_time(&self) -> TargetTime {
        self.end_time
    }

    /// Looks up actual exact target duration without inverting a rounded clock.
    pub fn lookup(&self, time: TargetTime) -> Result<ConvertedPhasePoint, ConvertedPhaseError> {
        if compare_time(time, self.retained_start_time()).is_lt() {
            return Err(ConvertedPhaseError::BeforeRetainedRange);
        }
        if compare_time(time, self.end_time).is_gt() {
            return Err(ConvertedPhaseError::AfterGeneratedRange);
        }
        let count = self
            .segments
            .partition_point(|segment| !compare_time(segment.start, time).is_gt());
        let segment = if count == 0 {
            Segment {
                start: self.initial_time,
                source: self.initial_source,
                state: ConvertedOutputState::Held,
            }
        } else {
            self.segments[count - 1]
        };
        Ok(ConvertedPhasePoint {
            source_rate: self.source_rate,
            segment,
            time,
        })
    }

    pub(super) fn preflight(
        &self,
        time: TargetTime,
        source: SourcePosition,
        state: ConvertedOutputState,
        nonempty: bool,
    ) -> Result<(), AudioError> {
        if time != self.end_time || source != self.end_source {
            return Err(AudioError::InvalidFormat);
        }
        if nonempty
            && self
                .segments
                .last()
                .is_none_or(|segment| segment.state != state)
            && self.segments.len() == self.capacity
        {
            return Err(AudioError::RenderCapacity);
        }
        Ok(())
    }

    pub(super) fn commit(
        &mut self,
        start: TargetTime,
        end: TargetTime,
        source_start: SourcePosition,
        source_end: SourcePosition,
        state: ConvertedOutputState,
        nonempty: bool,
    ) {
        if nonempty
            && self
                .segments
                .last()
                .is_none_or(|segment| segment.state != state)
        {
            self.segments.push(Segment {
                start,
                source: source_start,
                state,
            });
        }
        self.end_time = end;
        self.end_source = source_end;
    }
}

fn compare_time(a: TargetTime, b: TargetTime) -> Ordering {
    a.seconds().cmp(&b.seconds()).then_with(|| {
        (u128::from(a.numerator()) * u128::from(b.denominator()))
            .cmp(&(u128::from(b.numerator()) * u128::from(a.denominator())))
    })
}

/// Immutable generated correspondence with no public constructor.
/// Its source fraction may be wider than `SourcePosition`; elapsed calculation
/// preserves that exact fraction until one final nanosecond floor.
#[derive(Clone, Copy, Debug)]
pub struct ConvertedPhasePoint {
    source_rate: u32,
    segment: Segment,
    time: TargetTime,
}

impl ConvertedPhasePoint {
    /// Original immutable source frames per second.
    pub const fn source_rate(self) -> u32 {
        self.source_rate
    }
    /// Exact queried target duration.
    pub const fn target_time(self) -> TargetTime {
        self.time
    }
    /// Generated active conversion or explicit held output at this coordinate.
    pub const fn state(self) -> ConvertedOutputState {
        self.segment.state
    }

    /// Floors physical source duration relative to an integer source cut once.
    /// This does not remove paused source frames or qualify a native clock.
    pub fn elapsed_nanos_since(self, source_frame: u64) -> Result<i128, ConvertedPhaseError> {
        let rate = i128::from(self.source_rate);
        let frames = i128::from(self.segment.source.frame) - i128::from(source_frame);
        let denominator = u128::from(self.segment.source.denominator) * self.source_rate as u128;
        let residual = frames.rem_euclid(rate) as u128
            * u128::from(self.segment.source.denominator)
            + u128::from(self.segment.source.numerator);
        // Proper source duration denominator <=96 bits, scaled residual <=126.
        let scaled = residual * 1_000_000_000;
        let mut integer = frames.div_euclid(rate) * 1_000_000_000 + (scaled / denominator) as i128;
        let source_fraction = scaled % denominator;
        if self.segment.state == ConvertedOutputState::Active {
            let (query_integer, query_fraction) = split_nanos(self.time);
            let (start_integer, start_fraction) = split_nanos(self.segment.start);
            // All whole frame/second inputs are u64; even their summed scaled
            // magnitudes fit i128 with ample room for the final fraction carry.
            integer += query_integer - start_integer;
            // floor(fs + fq - ft). Cross products <=224 bits, sum <=225.
            let query_den = self.time.denominator();
            let start_den = self.segment.start.denominator();
            let positive = Wide::from_u128(source_fraction)
                .mul(query_den)
                .mul(start_den)
                .add(
                    Wide::from_u128(denominator)
                        .mul(query_fraction)
                        .mul(start_den),
                );
            let negative = Wide::from_u128(denominator)
                .mul(start_fraction)
                .mul(query_den);
            if positive.compare(negative).is_lt() {
                integer -= 1;
            } else {
                let whole = Wide::from_u128(denominator).mul(query_den).mul(start_den);
                if !positive.compare(negative.add(whole)).is_lt() {
                    integer += 1;
                }
            }
        }
        if integer < 0 {
            Err(ConvertedPhaseError::NegativeElapsed)
        } else {
            Ok(integer)
        }
    }
}

fn split_nanos(time: TargetTime) -> (i128, u64) {
    let scaled = u128::from(time.numerator()) * 1_000_000_000;
    (
        i128::from(time.seconds()) * 1_000_000_000
            + (scaled / u128::from(time.denominator())) as i128,
        (scaled % u128::from(time.denominator())) as u64,
    )
}

// Only fixed-size products/addition/comparison needed by the fraction carry.
// The proven 225-bit bound leaves room in four limbs; no heap bigint or divide.
#[derive(Clone, Copy)]
struct Wide([u64; 4]);
impl Wide {
    fn from_u128(value: u128) -> Self {
        Self([value as u64, (value >> 64) as u64, 0, 0])
    }
    fn mul(self, factor: u64) -> Self {
        let mut result = [0; 4];
        let mut carry = 0u128;
        for (index, limb) in self.0.into_iter().enumerate() {
            let product = u128::from(limb) * u128::from(factor) + carry;
            result[index] = product as u64;
            carry = product >> 64;
        }
        debug_assert_eq!(carry, 0);
        Self(result)
    }
    fn add(self, other: Self) -> Self {
        let mut result = [0; 4];
        let mut carry = 0u128;
        for (index, limb) in self.0.into_iter().enumerate() {
            let sum = u128::from(limb) + u128::from(other.0[index]) + carry;
            result[index] = sum as u64;
            carry = sum >> 64;
        }
        debug_assert_eq!(carry, 0);
        Self(result)
    }
    fn compare(self, other: Self) -> Ordering {
        self.0.iter().rev().cmp(other.0.iter().rev())
    }
}
